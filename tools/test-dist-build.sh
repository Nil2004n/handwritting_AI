#!/bin/sh
# Tests the distribution GENERATOR safeguards (not the archive contents; see test-dist.sh for that):
# refusal to touch unexpected files, clean regeneration without stale files, validator mutation checks,
# cleanDist scope, and that the default build does not create distributions.
# It regenerates linux-dist/ and win-dist/ (git-ignored build output) and finally leaves valid directories in place.
# Usage: sh tools/test-dist-build.sh        (needs models/: make models; run as your normal user)
set -u
ROOT=$(cd "$(dirname "$0")/.." && pwd -P); cd "$ROOT" || exit 2
PASS=0 FAIL=0
ok() { PASS=$((PASS+1)); printf 'PASS  %s\n' "$1"; }
bad() { FAIL=$((FAIL+1)); printf 'FAIL  %s\n' "$1"; [ -n "${2:-}" ] && printf '      %s\n' "$2"; }
t() { if [ "$2" = 0 ]; then ok "$1"; else bad "$1" "${3:-}"; fi; }
has() { case "$1" in *"$2"*) return 0 ;; esac; return 1; }
# run gradle capturing output and the REAL exit status
run() { OUT=$(./gradlew -q -Dorg.gradle.java.home=/usr/lib/jvm/java-21-openjdk-amd64 "$@" 2>&1); RC=$?; OUT=$(printf '%s' "$OUT" | grep -v Picked); }
lst() { ( cd "$1" && find . -type f | sort ); }

echo "== generation, clean regeneration"
run distLinux distWindows; t "dist generates both directories" $RC "$OUT"
before=$(lst linux-dist); run distLinux; t "regenerating replaces the directory" $RC "$OUT"
[ "$before" = "$(lst linux-dist)" ]; t "regeneration leaves exactly the same file set (no stale or extra files)" $?
[ -z "$(ls -A build/dist-staging/replaced 2>/dev/null)" ]; t "the replaced directory is cleaned up (no leftovers in staging)" $?

echo "== refuses to touch files it did not generate"
echo "precious" > linux-dist/MY-NOTES.txt
run distLinux; [ "$RC" != 0 ] && has "$OUT" "MY-NOTES.txt" && [ "$(cat linux-dist/MY-NOTES.txt)" = precious ]; t "distLinux stops and names the unexpected file; it is not deleted" $? "$OUT"
run cleanDist; [ "$RC" != 0 ] && [ -f linux-dist/MY-NOTES.txt ]; t "cleanDist refuses too" $? "$OUT"
rm -f linux-dist/MY-NOTES.txt
mv win-dist "$ROOT/.win-dist.held"; mkdir win-dist; echo foreign > win-dist/not-ours.txt
run distWindows; [ "$RC" != 0 ] && has "$OUT" "was not generated by this build" && [ -f win-dist/not-ours.txt ]; t "a directory this build did not generate is refused and untouched" $? "$OUT"
rm -rf win-dist; mv "$ROOT/.win-dist.held" win-dist

echo "== validator catches damage (mutation checks)"
run verifyDist; t "pristine directories validate" $RC "$OUT"
cp linux-dist/app/lib/xmpcore-6.1.11.jar /tmp/nbai-keep.jar; echo x >> linux-dist/app/lib/xmpcore-6.1.11.jar
run verifyDistLinux; [ "$RC" != 0 ] && has "$OUT" "checksum mismatch"; t "a modified payload file is detected" $? "$OUT"
cp /tmp/nbai-keep.jar linux-dist/app/lib/xmpcore-6.1.11.jar; rm -f /tmp/nbai-keep.jar
cp linux-dist/run-notebook-ai.sh /tmp/nbai-keep.sh; printf '# built in %s\n' "$ROOT" >> linux-dist/run-notebook-ai.sh
( cd linux-dist && sha256sum $(find . -type f ! -name SHA256SUMS | sed 's|^\./||' | sort) > SHA256SUMS )
run verifyDistLinux; [ "$RC" != 0 ] && has "$OUT" "developer-machine path"; t "an embedded absolute developer path is detected (even with valid checksums)" $? "$OUT"
cp /tmp/nbai-keep.sh linux-dist/run-notebook-ai.sh; rm -f /tmp/nbai-keep.sh
( cd win-dist && cp app/lib/javafx-base-21.0.7-win.jar /tmp/nbai-keep-fx.jar && cp app/lib/javafx-base-21.0.7-win.jar app/lib/javafx-base-21.0.7-linux.jar )
run verifyDistWindows; [ "$RC" != 0 ]; t "a foreign-platform JavaFX jar in win-dist is detected" $? "$OUT"
rm -f win-dist/app/lib/javafx-base-21.0.7-linux.jar /tmp/nbai-keep-fx.jar /tmp/nbai-keep.p
run distLinux distWindows; run verifyDist; t "regenerated and valid again after the mutation checks" $RC "$OUT"

echo "== default build is unchanged"
rm -rf linux-dist win-dist
run installDist; [ ! -e linux-dist ] && [ ! -e win-dist ] && [ -f build/install/notebook-ai/PLATFORM ]; t "installDist does not create or require the release directories" $? "$OUT"
run distLinux distWindows; t "directories can be regenerated after removal" $RC "$OUT"

echo "== missing models stop the build with an actionable message"
mv models "$ROOT/.models.held"; run distLinux; [ "$RC" != 0 ] && has "$OUT" "make models"; r=$?; mv "$ROOT/.models.held" models; t "no models: distLinux fails and tells you to run 'make models'" $r "$OUT"
[ -d linux-dist ]; t "a failed run left the previous linux-dist in place" $?

echo
echo "RESULT: $PASS passed, $FAIL failed"
[ "$FAIL" = 0 ] && echo "ALL CHECKS PASSED" || echo "SOME CHECKS FAILED"
[ "$FAIL" = 0 ]
